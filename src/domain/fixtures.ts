const s = (
  id: string,
  kind: RevisionSection["kind"],
  title: string,
  content: string,
  example?: string,
): RevisionSection => ({
  id,
  kind,
  title,
  content,
  ...(example ? { example } : {}),
});
const c = (
  id: string,
  subjectId: string,
  title: string,
  description: string,
  sections: RevisionSection[],
  status: Course["status"] = "published",
): Course => ({
  id,
  subjectId,
  title,
  description,
  sections,
  status,
  updatedAt: "2026-11-08T18:00:00.000Z",
  sources: [
    { id: id + "-source", name: "Cours d’exemple · démonstration locale" },
  ],
});
const q = (
  id: string,
  prompt: string,
  labels: string[],
  answer: number,
  explanation: string,
  hint: string,
  concept: string,
): Question => ({
  id,
  prompt,
  choices: labels.map((label, i) => ({ id: String(i), label })),
  correctChoiceId: String(answer),
  explanation,
  hint,
  concept,
});
